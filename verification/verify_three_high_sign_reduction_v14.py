#!/usr/bin/env python3
"""Exact algebra for v14 three-high sign reduction and beta boundary.

General inequalities are proved in the accompanying TeX. Polynomial identities
are checked by coefficient comparison. All 64 labelled positive-sign graphs
are classified. Seven fixed (s,t) boundary fibers are generated by the complete
divisor procedure, without a denominator/numerator cutoff.
"""
from collections import Counter
from fractions import Fraction as Q
from itertools import combinations
from math import gcd, isqrt
from pathlib import Path
import hashlib
import json


class Poly(dict):
    nvars = 8
    @staticmethod
    def cast(v):
        if isinstance(v, Poly): return v
        return Poly({(0,)*Poly.nvars: v}) if v else Poly()
    @staticmethod
    def variable(i):
        return Poly({tuple(int(j==i) for j in range(Poly.nvars)):1})
    def __add__(self, other):
        z=Counter(self)
        for m,c in self.cast(other).items(): z[m]+=c
        return Poly({m:c for m,c in z.items() if c})
    __radd__=__add__
    def __neg__(self): return Poly({m:-c for m,c in self.items()})
    def __sub__(self,other): return self+-self.cast(other)
    def __rsub__(self,other): return self.cast(other)+-self
    def __mul__(self,other):
        z=Counter()
        for a,c in self.items():
            for b,d in self.cast(other).items():
                z[tuple(x+y for x,y in zip(a,b))]+=c*d
        return Poly({m:c for m,c in z.items() if c})
    __rmul__=__mul__
    def __pow__(self,n):
        z=self.cast(1)
        for _ in range(n): z=z*self
        return z


identities=[]
def identity(name,lhs,rhs=0):
    assert Poly.cast(lhs)-Poly.cast(rhs)=={},name
    identities.append(name)

s,t,al,be,k,S,T,U=[Poly.variable(i) for i in range(8)]
u=s+t-1;A=s*al-t;b=s-t*be;C=s+u*k
delta=b*(A+1)-C*(A+b)
N=b*(A+1)*(be+1)*(k+1)-(b-1)*(C*al*be+b*k*(al+1))
first=-b*S+A*T+al*be
second=-C*S+(A+1)*U-k*(al+1)
third=(C-1)*T-(b-1)*U+(be+1)*(k+1)
identity('beta-nonnegative elimination',
         -C*(b-1)*first+b*(b-1)*second+b*(A+1)*third,
         -delta*T+N)
identity('beta-nonnegative strict numerator',N-delta,
         (s+be)*A+s+b*(b+be-1)
         +k*(u*A+al*(s+be*(s+b-1))+b*(be+1)))
identity('negative determinant upper-bound difference',
         delta-b*(1-b),-(C-b)*(A+b))

# beta=-1, arbitrary k: no division or singular-case omission in identities.
b=s+t;u=b-1;C=s+u*k
F=C*(A+b)-b*(A+1)
Sn=u*(A-al)*k-al*(s-1)*(A+1)
Tn=u*((al+b)*k-s*al)
Un=(C-1)*((al+b)*k-s*al)
identity('beta=-1 arbitrary-k first equation',-b*Sn+A*Tn,al*F)
identity('beta=-1 arbitrary-k second equation',-C*Sn+(A+1)*Un,k*(al+1)*F)
identity('beta=-1 arbitrary-k third equation',(C-1)*Tn,u*Un)
identity('beta=-1 strict T upper bound',F-Tn,
         (s-1)*(s*al+b)+t*t+u*k*(A-al))
identity('beta=-1 determinant lower bound',F-b*(b-1),(C-b)*(A+b))
identity('beta=-1 k-zero denominator',t*A-b*(s-1),
         s*t*al-(s*s+s*t+t*t-s-t))

# Complete beta=-1, k=0 rational formulas; all integers are obtained by filtering.
K0=s*s+s*t+t*t-s-t
G=s*t*al-K0
Sn=al*(s-1)*(A+1);Tn=al*s*u;Un=al*s*(s-1)
identity('boundary first equation',-b*Sn+A*Tn,al*G)
identity('boundary second equation',-s*Sn+(A+1)*Un)
identity('boundary third equation',(s-1)*Tn,u*Un)
identity('boundary first divisor certificate',t*Tn-u*G,K0*u)
identity('boundary second divisor certificate',t*Un-(s-1)*G,K0*(s-1))
identity('boundary S>U numerator',t*(A+1-s),G+s*(s-1))
q=[G+s*Sn,G+t*Tn,G+u*Un,G]
p=[[0,t*Sn+al*G,-u*Sn-(al+1)*G,-Sn],
   [s*Tn-G,0,-u*Tn,-Tn],
   [-s*Un,-t*Un-G,0,Un],
   [-s*G,-t*G,u*G,0]]
for i in range(4): identity(f'boundary scaled row {i}',sum(p[i]),-q[i])
for i,j in combinations(range(4),2):
    identity(f'boundary scaled pair {i},{j}',p[i][j]*p[j][i],q[i]*q[j]-G*G)
identity('P3 low-center inequality',
         (s+t+1)*(s*(t+1)+t*(s+1))-(s+t+1)*(s+1)*(t+1),
         (s+t+1)*(s*t-1))

# Every labelled simple graph on four vertices.
edges=list(combinations(range(4),2))
remaining=[];excluded=Counter();types=Counter()
for mask in range(64):
    es=[e for j,e in enumerate(edges) if mask>>j&1]
    adj=[set() for _ in range(4)]
    for i,j in es:adj[i].add(j);adj[j].add(i)
    deg=[len(a) for a in adj]
    reason=None
    if max(deg)>2:reason='negative row sum'
    elif deg[0]==0:reason='low row integer sum'
    elif deg.count(0)>=2:reason='two isolated vertices'
    elif any(i not in adj[0] and deg[i]==2 for i in range(1,4)):
        reason='negative low neighbor cannot have two positive entries'
    elif sorted(deg)==[0,1,1,2] and deg[0]==2:
        reason='P3 low-center strict inequality'
    if reason:
        excluded[reason]+=1
        continue
    if deg==[1,1,1,1]:kind='perfect_matching'
    elif sorted(deg)==[0,1,1,2] and deg[0]==1:kind='P3_low_endpoint'
    elif sorted(deg)==[1,1,2,2] and deg[0]==2:kind='P4_low_internal'
    elif sorted(deg)==[0,2,2,2] and deg[0]==2:kind='triangle_containing_low'
    else:raise AssertionError((mask,es,deg))
    types[kind]+=1
    remaining.append({'mask':mask,'edges':es,'degrees':deg,'type':kind})
assert dict(types)=={'perfect_matching':3,'P3_low_endpoint':6,'P4_low_internal':6,'triangle_containing_low':3}


def divisors(n):
    z=set()
    for d in range(1,isqrt(n)+1):
        if n%d==0:z.update((d,n//d))
    return sorted(z)


def exact_model(s,t,al,S,T,U):
    u=s+t-1
    q=[1+s*S,1+t*T,1+u*U,1]
    H=t*S+al;K=s*T-1
    p=[[0,H,-u*S-al-1,-S],[K,0,-u*T,-T],
       [-s*U,-t*U-1,0,U],[-s,-t,u,0]]
    assert all(sum(p[i])==-q[i] for i in range(4))
    assert all(p[i][j]*p[j][i]==q[i]*q[j]-1 for i,j in edges)
    w=[Q(q[0]),H+Q(1,2*K),u+Q(1,2*U),Q(1)]
    assert all(w[j]-w[i]*Q(p[i][j],q[i])>0 for i in range(4) for j in range(4) if i!=j)
    D=[-q[i]-sum(p[j][i] for j in range(4)) for i in range(4)]
    assert D[3]>0 and min(D[:3])<0
    return {'q':q,'p':p,'D':D,'weights':list(map(str,w)),
            'odd_denominators':all(x%2 for x in q)}


fibers=[]
for s,t in [(2,1),(2,5),(3,4),(4,3),(4,9),(5,6),(6,5)]:
    K0=s*s+s*t+t*t-s-t;bound=K0*gcd(s-1,t)
    trials=[];models=[]
    for G in divisors(bound):
        row={'G':G}
        if (G+K0)%(s*t):row['rejected']='alpha not integral'
        else:
            al=(G+K0)//(s*t)
            vals=[Q(al*(s-1)*(s*al-t+1),G),Q(al*s*(s+t-1),G),Q(al*s*(s-1),G)]
            row['alpha']=al
            row['S_T_U']=list(map(str,vals))
            if any(v.denominator!=1 for v in vals):row['rejected']='reverse entry not integral'
            else:
                S,T,U=map(int,vals)
                m=exact_model(s,t,al,S,T,U)
                m.update({'alpha':al,'G':G,'S_T_U':[S,T,U]})
                models.append(m);row['accepted']=True
        trials.append(row)
    fibers.append({'s':s,'t':t,'K0':K0,'divisor_integer':bound,
                   'all_trials':trials,'all_integer_models':models})

source_candidates=[Path(__file__).with_name('three_high_sign_reduction_v14.tex'),
                   Path(__file__).parent.parent/'paper/three_high_sign_reduction_v14.tex']
src=next(p for p in source_candidates if p.exists())
result={'version':'v14','passed':True,'polynomial_identities':len(identities),
        'identity_names':identities,'labelled_graphs_checked':64,
        'remaining_labelled_graphs':remaining,'remaining_types':dict(types),
        'excluded_graph_counts':dict(excluded),'complete_fixed_boundary_fibers':fibers,
        'exact_boundary_models':sum(len(f['all_integer_models']) for f in fibers),
        'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),
        'script_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'limitations':['Four sign types are necessary cases, not existence claims.',
                       'Beta bounds and boundary classification assume the positive perfect-matching type.',
                       'The general perfect-matching theorem and all-high-D sign problem remain open.',
                       'The seven selected (s,t) fibers illustrate the complete divisor procedure; they are not all boundary models.']}
out=Path(__file__).with_name('three_high_sign_reduction_verification_v14.json')
out.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'passed':True,'polynomial_identities':len(identities),
                  'remaining_sign_graphs':len(remaining),
                  'complete_boundary_fibers':len(fibers),
                  'exact_boundary_models':result['exact_boundary_models']}))
